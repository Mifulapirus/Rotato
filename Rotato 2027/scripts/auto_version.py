import os
import re
import textwrap
from datetime import datetime

# PlatformIO pre-build script — runs before compilation on every build.
#
# Firmware version = MAJOR.BUILD  (e.g. "2.0", "2.1", "2.2" …)
#   MAJOR — set by hand in src/version.h
#   BUILD — counts every build of this MAJOR, starting at 0. It restarts at 0
#           automatically when MAJOR changes. The last build made is stored in
#           build_number.txt as "MAJOR.BUILD" (empty file = nothing built yet).
#
# PCB revision — the hardware this firmware is built for. It is read from the
# KiCad board's title block ("Rev" field, File → Page Settings in the PCB
# editor) when the Electronics folder of the main Rotato repo is next to this
# firmware. Otherwise (firmware cloned on its own) the fallback
# PCB_REVISION in src/version.h is used.
#
# Writes src/version_build.h.
Import("env")  # noqa: F821 — injected by SCons/PlatformIO

# KiCad board for this firmware, relative to the firmware project folder.
KICAD_PCB = os.path.join("..", "..", "Electronics", "rotato 2027", "rotato 2027.kicad_pcb")


def read_version_h(src_dir):
    """Return (major, fallback_pcb_revision) from src/version.h."""
    major, pcb = 2, "?"
    path = os.path.join(src_dir, "version.h")
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            content = f.read()
        m = re.search(r"#define\s+FW_VERSION_MAJOR\s+(\d+)", content)
        if m:
            major = int(m.group(1))
        m = re.search(r'#define\s+PCB_REVISION\s+"([^"]*)"', content)
        if m:
            pcb = m.group(1)
    return major, pcb


def read_kicad_revision(project_dir):
    """Return the title-block revision of the KiCad board, or None."""
    path = os.path.normpath(os.path.join(project_dir, KICAD_PCB))
    if not os.path.exists(path):
        return None
    with open(path, "r", encoding="utf-8", errors="replace") as f:
        content = f.read()
    m = re.search(r'\(title_block\b.*?\(rev\s+"([^"]*)"\)', content, re.S)
    return m.group(1).strip() if m and m.group(1).strip() else None


def next_build(project_dir, major):
    """Next build number for this MAJOR; saves it as the last build made."""
    counter_file = os.path.join(project_dir, "build_number.txt")
    build = 0
    if os.path.exists(counter_file):
        with open(counter_file, "r") as f:
            m = re.match(r"\s*(\d+)\.(\d+)\s*$", f.read())
        if m and int(m.group(1)) == major:
            build = int(m.group(2)) + 1
    with open(counter_file, "w") as f:
        f.write("{}.{}\n".format(major, build))
    return build


# ── Main ──────────────────────────────────────────────────────────────────────
# Only real builds count. The VS Code PlatformIO extension also runs this
# script when it re-indexes the project (IntelliSense), and "pio run -t clean"
# runs it too; neither should use up a build number.
from SCons.Script import COMMAND_LINE_TARGETS  # noqa: E402

def main():
    project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
    src_dir = env.subst("$PROJECT_SRC_DIR")  # noqa: F821

    major, pcb_fallback = read_version_h(src_dir)
    pcb_kicad = read_kicad_revision(project_dir)
    if pcb_kicad:
        pcb, pcb_source = pcb_kicad, "kicad"
        if pcb_kicad != pcb_fallback:
            print("[version] NOTE: KiCad says PCB rev {} but src/version.h says {} - using KiCad. "
                  "Update PCB_REVISION in src/version.h so standalone builds agree.".format(pcb_kicad, pcb_fallback))
    else:
        pcb, pcb_source = pcb_fallback, "version.h"

    build = next_build(project_dir, major)
    now = datetime.now()

    header = textwrap.dedent("""\
    #pragma once
    // Auto-generated by scripts/auto_version.py - DO NOT EDIT
    // This file is overwritten on every build. Edit src/version.h instead.

    #define FW_VERSION_MAJOR   {major}
    #define FW_BUILD_NUMBER    {build}
    #define FW_VERSION_FULL    "{major}.{build}"     // e.g. "2.0"
    #define PCB_REVISION_STR   "{pcb}"               // board this firmware is built for
    #define PCB_REVISION_FROM  "{src}"               // "kicad" or "version.h"
    #define FW_BUILD_DATE      "{date}"
    #define FW_BUILD_TIME      "{time}"
    """).format(
        major=major, build=build, pcb=pcb, src=pcb_source,
        date=now.strftime("%Y-%m-%d"), time=now.strftime("%H:%M:%S"),
    )

    out_path = os.path.join(src_dir, "version_build.h")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(header)

    print(
        "\n[version] Rotato firmware {}.{}  for PCB rev {} (from {})  {} {}\n".format(
            major, build, pcb, pcb_source,
            now.strftime("%Y-%m-%d"), now.strftime("%H:%M:%S"),
        )
    )


if not (env.IsIntegrationDump() or "clean" in COMMAND_LINE_TARGETS or "cleanall" in COMMAND_LINE_TARGETS):  # noqa: F821
    main()
